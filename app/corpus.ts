// File I/O for the step-sequence corpus (data/sequences/*.json). The core
// (sequencer/corpus.ts, design/costmodel.ts) never touches the filesystem.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { type Report, evaluate, fitCostModel } from "../design/costmodel.ts";
import { MIN_FIT_MODELS } from "../design/estimate.ts";
import { type SequenceRecord, validateRecord } from "../sequencer/corpus.ts";

export const SEQ_DIR = join("data", "sequences");
export const FITTED_FILE = join("design", "fitted.ts");

export interface LoadedFile {
  file: string;
  ok: boolean;
  errors: string[];
  record?: SequenceRecord;
}

export function loadCorpus(dir: string = SEQ_DIR): LoadedFile[] {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .map((f) => {
      try {
        const v = validateRecord(JSON.parse(readFileSync(join(dir, f), "utf8")));
        return v.ok ? { file: f, ok: true, errors: [], record: v.record } : { file: f, ok: false, errors: v.errors };
      } catch (e) {
        return { file: f, ok: false, errors: [`unreadable: ${e instanceof Error ? e.message : String(e)}`] };
      }
    });
}

export function formatReport(r: Report): string {
  const L: string[] = [];
  L.push(`${r.published_count} of ${r.target} published sequences`);
  L.push(`exit test (+-${r.tolerance_pct}% on ${r.target} published sequences): ${r.exit_test}`);
  if (r.status !== "ok") {
    L.push(`status: ${r.status} - ${r.note}`);
    return L.join("\n");
  }
  const table = (rows: Report["loo"]) => {
    for (const x of rows) L.push(`  ${x.model.padEnd(28)} published ${String(x.published).padStart(4)}  predicted ${x.predicted.toFixed(1).padStart(7)}  ${x.err_pct.toFixed(1).padStart(7)}%  ${x.pass ? "pass" : "FAIL"}`);
  };
  L.push("leave-one-out (each model predicted from a fit on the others):");
  table(r.loo);
  L.push(`${r.in_sample_label}:`);
  table(r.in_sample);
  L.push(r.note);
  return L.join("\n");
}

export function fittedFileText(c: ReturnType<typeof fitCostModel>): string {
  return `// Generated by \`npm run origami -- corpus fit --write\`. Do not edit by hand.
// null = no fit yet (fewer than MIN_FIT_MODELS published sequences).
import type { FittedConstants } from "./costmodel.ts";

export const FITTED: FittedConstants | null = ${JSON.stringify(c, null, 2)};
`;
}

/** Entry point for `corpus <validate|report|fit>`. Returns the process exit code. */
export function corpusCommand(sub: string | undefined, args: string[]): number {
  const files = loadCorpus();
  if (sub === "validate") {
    let bad = 0;
    for (const f of files) {
      if (f.ok) console.log(`ok    ${f.file}${f.record!.published ? "" : " (unpublished)"}`);
      else {
        bad++;
        console.log(`FAIL  ${f.file}`);
        for (const e of f.errors) console.log(`        ${e}`);
      }
    }
    console.log(`${files.length - bad} of ${files.length} valid`);
    return bad ? 1 : 0;
  }
  const valid = files.filter((f) => f.ok).map((f) => f.record!);
  if (sub === "report") {
    for (const f of files) if (!f.ok) console.log(`skipped invalid ${f.file}`);
    console.log(formatReport(evaluate(valid)));
    return 0;
  }
  if (sub === "fit") {
    const write = args.includes("--write");
    const force = args.includes("--force");
    const pub = valid.filter((r) => r.published);
    if (pub.length < MIN_FIT_MODELS && !force) {
      console.error(`refusing to fit: ${pub.length} published sequences, need ${MIN_FIT_MODELS} (--force prints a fit without writing)`);
      return 1;
    }
    let c;
    try {
      c = fitCostModel(pub);
    } catch (e) {
      console.error(`insufficient data: ${e instanceof Error ? e.message : String(e)}`);
      return 1;
    }
    console.log(JSON.stringify(c, null, 2));
    if (pub.length < MIN_FIT_MODELS) {
      console.log(`--force: ${pub.length} < ${MIN_FIT_MODELS} published sequences, nothing written`);
      return 0;
    }
    if (write) {
      writeFileSync(FITTED_FILE, fittedFileText(c));
      console.log(`wrote ${FITTED_FILE}`);
    } else console.log("(dry run; pass --write to regenerate design/fitted.ts)");
    return 0;
  }
  console.error("usage: origami corpus <validate|report|fit [--write] [--force]>");
  return 1;
}
